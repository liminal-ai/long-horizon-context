#!/usr/bin/env node
// Sends small source transcripts through the production path (cc-lhc intake mapping, lhc intake,
// drain, compact and session view, cc-lhc rollout writer) and writes, per case, the source
// transcript, the rebuilt transcript and the session view the writer rendered from, so the content
// check is graded on real rebuilds.
// usage: roundtrip.mjs SCRATCH_DIR OUT_DIR
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { annotatedSessionView } from "./read-seam-view.mjs";

const root = new URL("../../../../", import.meta.url);
const lhc = await import(new URL("packages/lhc/dist/index.js", root).href);
const { mapRolloutLines } = await import(new URL("packages/cc-lhc/dist/intake/map.js", root).href);
const { compactConstruction } = await import(new URL("packages/cc-lhc/dist/governor/band-allocation.js", root).href);
const { buildRolloutLines, runtimeNoteRolloutLine, serializeRolloutLines } = await import(
  new URL("packages/cc-lhc/dist/rollout/rebuild.js", root).href
);

const [scratchRoot, out] = process.argv.slice(2);
const must = (r) => {
  if (!r.ok) throw new Error(JSON.stringify(r.error));
  return r.value;
};
const user = (uuid, content, extra = {}) => ({ type: "user", uuid, ...extra, message: { role: "user", content } });
const assistant = (uuid, texts, model = "claude-opus-5-5") => ({
  type: "assistant",
  uuid,
  message: { role: "assistant", model, content: texts.map((text) => ({ type: "text", text })) },
});
const marker = {
  eventKind: "compact_continuation_marker",
  idempotencyKey: "roundtrip-continuation",
  actor: "system",
  harness: "cc",
  payload: {
    kind: "lhc.compact_continuation",
    cause: "context_compacted_task_in_progress",
    action: "continue_existing_task",
    newUserRequest: false,
    waitForUser: false,
    continuationTurnId: "t2",
  },
};

// Each turn is { lines, events? }; compactAfter compacts the view after that many turns.
const CASES = {
  multiblock: {
    turns: [{ lines: [user("u1", "Please compare alpha and beta."), assistant("a1", ["Alpha is first.", "Beta is second."])] }],
  },
  "user-multiblock": {
    turns: [
      {
        lines: [
          user("u1", [
            { type: "text", text: "Please compare " },
            { type: "text", text: "alpha and beta." },
          ]),
          assistant("a1", ["Alpha is first; beta is second."]),
        ],
      },
    ],
  },
  chrome: {
    turns: [
      {
        lines: [user("u1", "Remember the codeword ALDER-7."), assistant("a1", ["Noted."])],
      },
      {
        lines: [
          user("m1", "<local-command-caveat>Caveat: generated by a local command.</local-command-caveat>", { isMeta: true }),
          user("m2", "<command-name>/model</command-name>\n<command-message>model</command-message>"),
          user("m3", "<local-command-stdout>Set model to opus</local-command-stdout>"),
          assistant("s1", ["No response requested."], "<synthetic>"),
          user("u2", "What is the codeword?"),
          assistant("a2", ["The codeword is ALDER-7."]),
        ],
      },
    ],
  },
  continuation: {
    turns: [
      {
        lines: [user("u1", "Please continue the existing task."), assistant("a1", ["I will continue."])],
        events: [marker],
      },
    ],
  },
  collision: {
    compactAfter: 1,
    turns: [
      { lines: [user("u1", "What should the enabled setting be?"), assistant("a1", ["The setting should be yes."])] },
      { lines: [user("u2", "yes"), assistant("a2", ["Done."])] },
    ],
  },
  "prior-note": {
    turns: [
      {
        lines: [
          user("u1", "prompt1"),
          assistant("a1", ["answer1"]),
          user("n1", "[runtime note] [lhc compact:auto] earlier receipt"),
        ],
      },
      { lines: [user("u2", "prompt2"), assistant("a2", ["answer2"])] },
    ],
  },
};

const sdk = lhc.initLhc({
  mode: "manual",
  tokenFamily: "claude-2026",
  inferenceCallbacks: lhc.createDeterministicInferenceCallbacks(),
});
for (const [name, spec] of Object.entries(CASES)) {
  const scratch = mkdtempSync(join(scratchRoot, `roundtrip-${name}-`));
  const ref = { filePath: join(scratch, "thread.sqlite") };
  must(await lhc.threads.newThread({ ...ref, registryPath: join(scratch, "registry.sqlite"), cwd: scratch, title: name }));
  const source = [];
  for (const [i, turn] of spec.turns.entries()) {
    const events = mapRolloutLines(turn.lines).events;
    events.push(...(turn.events ?? []), {
      eventKind: "turn_end",
      idempotencyKey: `${name}-turn-end-${i}`,
      actor: "system",
      harness: "cc",
      payload: {},
    });
    must(await sdk.intakeStream.messageEvents(ref, events));
    must(await sdk.work.drain(ref));
    source.push(...turn.lines);
    if (spec.compactAfter === i + 1) {
      must(await sdk.threadView.compact(ref, compactConstruction({ profile: "default", lowerBoundTokens: 10 })));
    }
  }
  const view = await annotatedSessionView(ref);
  const envelope = { cwd: scratch, version: "2.1.317" };
  const sid = "00000000-0000-4000-8000-000000000002";
  const rebuilt = buildRolloutLines({ entries: view.entries, newSessionId: sid, envelope });
  rebuilt.push(runtimeNoteRolloutLine(`${name} roundtrip`, sid, envelope, rebuilt.at(-1).line.uuid));
  writeFileSync(join(out, `${name}-source.jsonl`), source.map((l) => JSON.stringify(l)).join("\n") + "\n");
  writeFileSync(join(out, `${name}-rebuilt.jsonl`), serializeRolloutLines(rebuilt));
  writeFileSync(join(out, `${name}-view.json`), JSON.stringify(view, null, 2));
  rmSync(scratch, { recursive: true, force: true });
  console.log(`wrote ${name} (${view.entries.length} view entries, ${rebuilt.length} rebuilt lines)`);
}
